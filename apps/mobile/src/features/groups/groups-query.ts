import type { NewGroup } from '@split-pay/shared';
import { queryOptions, useMutation, useQueryClient } from '@tanstack/react-query';
import { type InferResponseType, parseResponse } from 'hono/client';
import { api } from '@/lib/api';

/**
 * Query keys of group data. Everything about one group lives under
 * `['groups', groupId, …]`, so invalidating `groupKeys.detail(id)` refreshes
 * the group and whatever later slices hang below it (entries, balances).
 */
export const groupKeys = {
  all: ['groups'] as const,
  list: () => [...groupKeys.all, 'list'] as const,
  detail: (groupId: string) => [...groupKeys.all, groupId] as const,
};

/** The inbox: my groups, most recent activity first (GET /groups). */
export const groupsQuery = () =>
  queryOptions({
    queryKey: groupKeys.list(),
    queryFn: () => parseResponse(api.groups.$get()),
  });
export type GroupListItem = InferResponseType<typeof api.groups.$get, 200>[number];

/** One group with its members (GET /groups/:groupId). */
export const groupQuery = (groupId: string) =>
  queryOptions({
    queryKey: groupKeys.detail(groupId),
    queryFn: () => parseResponse(api.groups[':groupId'].$get({ param: { groupId } })),
  });
export type GroupDetail = InferResponseType<(typeof api.groups)[':groupId']['$get'], 200>;

/** Creates a group; the id is generated by the caller so a retry cannot duplicate it. */
export function useCreateGroup() {
  const queryClient = useQueryClient();
  return useMutation({
    mutationFn: (input: NewGroup) => parseResponse(api.groups.$post({ json: input })),
    onSuccess: async () => {
      await queryClient.invalidateQueries({ queryKey: groupKeys.list() });
    },
  });
}
